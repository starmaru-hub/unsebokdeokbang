def four_grids(surname: list[int], given: list[int]) -> dict:
    """원형이정 4격.
    원격(元, 초년) = 이름 획수 합    형격(亨, 청년) = 성 + 이름 첫 자
    이격(利, 중년) = 성 + 이름 끝 자  정격(貞, 총운·말년) = 성명 전체
    외자 이름은 원격=이름, 이격=이름+1(가성수) 관례를 따른다.
    """
    s = sum(surname)
    if len(given) == 1:
        g = given[0]
        won, hyeong, i_, jeong = g + 1, s + g, g + 1, s + g
    else:
        won, hyeong, i_, jeong = sum(given), s + given[0], s + sum(given[1:]), s + sum(given)
    return {
        "won": {"label": "원격(초년운)", **suri_info(won)},
        "hyeong": {"label": "형격(청년운)", **suri_info(hyeong)},
        "i": {"label": "이격(중년운)", **suri_info(i_)},
        "jeong": {"label": "정격(총운)", **suri_info(jeong)},
    }
