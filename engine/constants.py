def ganji_name(idx60: int) -> str:
    return GAN[idx60 % 10] + JI[idx60 % 12]


def ganji_kr(idx60: int) -> str:
    return GAN_KR[idx60 % 10] + JI_KR[idx60 % 12]


def ganji_index(gan: int, ji: int) -> int:
    """천간·지지 번호 → 60갑자 번호 (같은 음양이어야 함)."""
    for k in range(60):
        if k % 10 == gan and k % 12 == ji:
            return k
    raise ValueError("천간과 지지의 음양이 맞지 않습니다")
